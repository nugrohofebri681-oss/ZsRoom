// Concept-only route: exploration boards are validated for provenance, integrity, privacy and ownership —
// never as production sprites — and can never pass the strict production validator. Synthetic fixtures only.
import { createHash } from 'node:crypto';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import sharp from 'sharp';
import { describe, expect, it } from 'vitest';
// @ts-expect-error — plain ESM pipeline modules
import { loadSpecs, ownershipViolations } from '../../scripts/lib.mjs';
// @ts-expect-error — plain ESM pipeline modules
import { validateConcept } from '../../scripts/validate-concept.mjs';
// @ts-expect-error — plain ESM pipeline modules
import { validateSubmission } from '../../scripts/validate-submission.mjs';

const specs = loadSpecs();
const sha = (p: string) => createHash('sha256').update(readFileSync(p)).digest('hex');
const board = () => sharp({ create: { width: 64, height: 48, channels: 3, background: '#e8a0b4' } }).png().toBuffer();

async function concept(opts: { exif?: boolean; tamper?: boolean; type?: string } = {}) {
  const root = mkdtempSync(join(tmpdir(), 'zs-concept-'));
  const dir = join(root, 'art', 'concepts', 'char_zila', 'v001');
  mkdirSync(join(dir, 'sources'), { recursive: true });
  let png = await board();
  if (opts.exif) png = await sharp(png).withMetadata({ exif: { IFD0: { Artist: 'someone', ImageDescription: 'test' } } }).png().toBuffer();
  writeFileSync(join(dir, 'board.png'), png);
  writeFileSync(join(dir, 'sources', 'a.png'), await board());
  const meta = {
    assetId: 'char_zila', version: 'v001', submissionType: opts.type ?? 'concept', author: 'codex', createdAt: new Date().toISOString(),
    generator: { tool: 'synthetic-test-fixture' }, provenance: 'Synthetic test fixture generated by the unit test.', cost: 'none',
    files: { board: { path: 'board.png', sha256: opts.tamper ? '0'.repeat(64) : sha(join(dir, 'board.png')) },
      sources: [{ path: 'art/concepts/char_zila/v001/sources/a.png', sha256: sha(join(dir, 'sources', 'a.png')) }] },
  };
  writeFileSync(join(dir, 'metadata.json'), JSON.stringify(meta));
  return { root, dir };
}

describe('concept-only validation route', () => {
  it('a well-formed concept board passes concept checks', async () => {
    const { root, dir } = await concept();
    const r = await validateConcept({ assetId: 'char_zila', version: 'v001', dir }, specs, root);
    expect(r.errors).toEqual([]);
    expect(r.kind).toBe('concept');
  });
  it('integrity: a board that does not match its recorded checksum fails', async () => {
    const { root, dir } = await concept({ tamper: true });
    const r = await validateConcept({ assetId: 'char_zila', version: 'v001', dir }, specs, root);
    expect(r.errors.join()).toMatch(/board sha256/);
  });
  it('privacy: images carrying EXIF metadata fail', async () => {
    const { root, dir } = await concept({ exif: true });
    const r = await validateConcept({ assetId: 'char_zila', version: 'v001', dir }, specs, root);
    expect(r.errors.join()).toMatch(/privacy: no EXIF/);
  });
  it('must declare itself a concept', async () => {
    const { root, dir } = await concept({ type: 'production' });
    const r = await validateConcept({ assetId: 'char_zila', version: 'v001', dir }, specs, root);
    expect(r.errors.join()).toMatch(/declared as a concept/);
  });
  it('the strict production validator still rejects a concept board in art/submissions (never weakened)', async () => {
    const { dir } = await concept();
    writeFileSync(join(dir, 'char_zila_v001.png'), readFileSync(join(dir, 'board.png')));
    const meta = JSON.parse(readFileSync(join(dir, 'metadata.json'), 'utf8'));
    meta.specVersion = specs.get('char_zila').spec.specVersion;
    meta.files.master = { path: 'char_zila_v001.png', sha256: sha(join(dir, 'char_zila_v001.png')) };
    writeFileSync(join(dir, 'metadata.json'), JSON.stringify(meta));
    const r = await validateSubmission({ assetId: 'char_zila', version: 'v001', dir }, specs);
    expect(r.errors.join()).toMatch(/production submission \(not a concept board\)/);
    expect(r.errors.join()).toMatch(/canvas size/);                       // sprite rules still apply in full
  });
  it('ownership: concept branches may only touch their own concept folder', () => {
    expect(ownershipViolations('codex/art/char-zila-concept-r1', ['art/concepts/char_zila/v001/board.png'])).toEqual([]);
    expect(ownershipViolations('codex/art/char-zila-concept-r1', ['art/submissions/char_zila/v001/char_zila_v001.png'])).toHaveLength(1);
    expect(ownershipViolations('codex/art/char-zila-concept-r1', ['art/concepts/char_febri/v001/board.png'])).toHaveLength(1);
    expect(ownershipViolations('claude/some-branch', ['art/concepts/char_zila/v001/board.png'])).toHaveLength(1);
  });
});
